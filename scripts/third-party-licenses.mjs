// Regenerates THIRD_PARTY_LICENSES.md: the licence texts of every Rust crate and npm package
// compiled into Pulse. Run from the repository root after `npm ci`, with cargo-about installed
// (`cargo install --locked cargo-about`):
//
//   node scripts/third-party-licenses.mjs
//
// Rerun whenever Cargo.lock or package-lock.json changes, and commit the result.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const output = join(root, "THIRD_PARTY_LICENSES.md");

function rust() {
  return execFileSync(
    "cargo",
    ["about", "generate", "--locked", "--workspace", "-c", "scripts/licenses/about.toml", "scripts/licenses/about.hbs"],
    { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024, stdio: ["ignore", "pipe", "inherit"] },
  ).trim();
}

/** Every installed package the production bundle can include (paths from `npm ls --parseable`). */
function npmPackages() {
  const listing = execFileSync("npm", ["ls", "--omit=dev", "--all", "--parseable"], {
    cwd: root,
    encoding: "utf8",
    shell: process.platform === "win32",
  });
  const seen = new Map();
  for (const directory of listing.split(/\r?\n/).slice(1).filter(Boolean)) {
    const { name, version, license } = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
    seen.set(`${name}@${version}`, { name, version, license, directory });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function licenceText(directory) {
  const files = readdirSync(directory).filter((f) => /^(licen[cs]e|copying)/i.test(f)).sort();
  return files.map((f) => readFileSync(join(directory, f), "utf8").trim()).join("\n\n");
}

function npm() {
  const sections = [];
  for (const { name, version, license, directory } of npmPackages()) {
    let text = licenceText(directory);
    // Tauri's plugins publish only an SPDX expression; the text is the one the Tauri API package ships.
    if (!text && name.startsWith("@tauri-apps/") && existsSync(join(root, "node_modules/@tauri-apps/api"))) {
      text = licenceText(join(root, "node_modules/@tauri-apps/api"));
    }
    if (!text) throw new Error(`No licence text found for ${name}@${version}`);
    sections.push(`### ${name} ${version}\n\nLicence: ${license}\n\n\`\`\`text\n${text}\n\`\`\`\n`);
  }
  return sections.join("\n");
}

const document = `# Third-Party Licences

Generated by \`scripts/third-party-licenses.mjs\`; do not edit by hand. These are the licences of
the open-source Rust crates and npm packages compiled into Pulse for Windows. Icons, marks and
other material are listed in THIRD_PARTY_NOTICES.md.

## Rust crates

${rust()}

## npm packages

${npm()}`;

writeFileSync(output, document.replace(/\r\n/g, "\n").replace(/\n{3,}/g, "\n\n"));
console.log(`Wrote ${output}`);
